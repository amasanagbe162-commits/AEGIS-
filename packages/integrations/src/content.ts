import { renderMasterMarkdown, type Rule, type Severity } from "@aegis/core";
import type { InstructionInput } from "./types.js";

/** Size budgets in bytes (UTF-8). Tests enforce them. */
export const FULL_BUDGET_BYTES = 24 * 1024;
/** Codex shares one 32 KiB budget across every AGENTS.md it loads, so AEGIS stays well below that. */
export const COMPACT_BUDGET_BYTES = 6 * 1024;
/** ChatGPT custom instruction fields were limited to 1,500 characters. Stay under that to be safe. */
export const CHATGPT_BUDGET_CHARS = 1500;

const SEVERITY_RANK: Record<Severity, number> = {
  critical: 0,
  high: 1,
  medium: 2,
  low: 3,
  informational: 4,
};

const byteLength = (s: string) => Buffer.byteLength(s, "utf8");

function sortedRules(rules: readonly Rule[]): Rule[] {
  return [...rules].sort(
    (a, b) => SEVERITY_RANK[a.severity] - SEVERITY_RANK[b.severity] || a.id.localeCompare(b.id),
  );
}

function verificationSection(input: InstructionInput): string[] {
  return [
    "## How to verify your work",
    "",
    `Run \`${input.checkCommand}\` after you change code. It runs the checks planned for the **${input.level}** protection level and reports what actually ran.`,
    "",
    "- Exit code 0: every planned check ran and nothing blocking was found.",
    "- Exit code 1: blocking findings. Investigate the root cause, fix it, and run the check again.",
    "- Exit code 2: the command could not run (invalid files or usage). Fix the setup first.",
    "- Exit code 3: INCOMPLETE. Some checks did not run (for example a scanner is not installed). This is not a pass.",
    "",
    `Stop after ${input.maxAttempts} failed attempts at the same problem and report it as unresolved instead of looping.`,
    "A scanner finding is evidence to investigate. It is not proof of a vulnerability, and a clean result is not proof of safety.",
    "",
  ];
}

function reportSection(): string[] {
  return [
    "## Finish every task with an AEGIS report",
    "",
    "- **Changed:** the files you changed and why.",
    "- **Verified:** the checks that ran and passed (command and result).",
    "- **Not verified:** checks you did not run or could not run, with the reason.",
    "- **Open risks:** unresolved findings, failing tests that were already failing, and anything you are unsure about.",
    "",
    "Never write that something is fixed, secure or verified unless a check you ran shows it.",
    "",
  ];
}

function ruleDetail(rule: Rule, examples: "both" | "safe" | "none"): string[] {
  const out: string[] = [
    `### ${rule.id} (${rule.severity}): ${rule.title}`,
    "",
    `Applies when: ${rule.appliesWhen}`,
    "",
    "Do:",
    ...rule.prevention.map((p) => `- ${p}`),
    "",
    "Verify:",
    ...rule.verification.map((v) => `- ${v}`),
    "",
  ];
  const fence = (lang: string, code: string) => ["```" + lang, code.trimEnd(), "```", ""];
  if (examples === "both") {
    out.push(
      "Unsafe:",
      ...fence(rule.badExample.language, rule.badExample.code),
      "Safe:",
      ...fence(rule.goodExample.language, rule.goodExample.code),
    );
  } else if (examples === "safe") {
    out.push("Safe:", ...fence(rule.goodExample.language, rule.goodExample.code));
  }
  if (rule.limitations.length > 0) {
    out.push(`Limits: ${rule.limitations[0] ?? ""}`, "");
  }
  return out;
}

type Detail = "both" | "safe" | "none" | "summary";

function summaryLine(r: Rule): string {
  return `- **${r.id}** (${r.severity}) ${r.title}. Applies when: ${r.appliesWhen} Do: ${r.prevention[0] ?? r.description}`;
}

function renderFull(input: InstructionInput, detail: Detail, maxRules = Infinity): string {
  const rules = sortedRules(input.rules);
  const out: string[] = [
    `> Generated by AEGIS from \`${input.masterFileName}\` (protection level: ${input.level}).`,
    "> Do not edit this file by hand: change the master file or rules and run `aegis agents sync`.",
    "> These instructions are advisory. Deterministic checks, not this text, are the evidence.",
    "",
    // The shared renderer already covers operating rules, self-correction, severity and limitations.
    renderMasterMarkdown(input.master, []).trimEnd(),
    "",
    ...verificationSection(input),
    ...reportSection(),
  ];
  const lessons = input.lessons ?? [];
  if (lessons.length > 0) {
    out.push(
      "## Lessons approved for this project",
      "",
      "Mistakes seen here before, reviewed by a person. Do not repeat them.",
      "",
      ...lessons.map((l) => `- **${l.id} ${l.title}:** ${l.guidance}`),
      "",
    );
  }
  if (rules.length > 0) {
    out.push("## Protection rules for this project", "");
    if (detail === "summary") {
      const shown = rules.slice(0, maxRules);
      out.push(...shown.map(summaryLine));
      if (shown.length < rules.length) {
        out.push(
          `- ${rules.length - shown.length} more rule(s): run \`aegis rules list\` for the full list.`,
        );
      }
      out.push("");
    } else {
      for (const r of rules) out.push(...ruleDetail(r, detail));
    }
  }
  return out.join("\n").trimEnd() + "\n";
}

/**
 * Full instructions for agents that read a dedicated instructions file (Claude Code rules,
 * Copilot path-specific instructions). If the text would exceed the size budget, detail is
 * reduced step by step: unsafe examples first, then all examples, then per-rule guidance down to
 * one line, and only as a last resort are the lowest-severity rules left out (and counted).
 */
export function buildFullInstructions(input: InstructionInput): string {
  for (const detail of ["both", "safe", "none", "summary"] as const) {
    const text = renderFull(input, detail);
    if (byteLength(text) <= FULL_BUDGET_BYTES) return text;
  }
  for (let n = input.rules.length - 1; n >= 0; n--) {
    const text = renderFull(input, "summary", n);
    if (byteLength(text) <= FULL_BUDGET_BYTES) return text;
  }
  return renderFull(input, "summary", 0);
}

/** Short instructions for AGENTS.md (read by OpenAI Codex and others). */
export function buildCompactInstructions(input: InstructionInput): string {
  const { master } = input;
  const rules = sortedRules(input.rules);

  const head: string[] = [
    "## AEGIS protection rules",
    "",
    `Generated by AEGIS from \`${input.masterFileName}\` (level: ${input.level}). Advisory: checks give the evidence.`,
    "",
    `**${master.principle}**`,
    "",
  ];
  const operating = master.operatingRules.map(
    (r) => `- **${r.title}:** ${r.instructions[0] ?? ""}`,
  );
  const dangerous =
    master.dangerousOperations.length > 0
      ? [
          "",
          `Ask the user before: ${master.dangerousOperations.map((d) => d.toLowerCase()).join("; ")}.`,
        ]
      : [];
  const verify = [
    "",
    `**Verify:** run \`${input.checkCommand}\` after code changes (0 clean, 1 findings, 2 cannot run, 3 incomplete: not a pass). After ${input.maxAttempts} failed attempts at one problem, stop and report it.`,
    "",
    "**Finish with:** Changed / Verified (command and result) / Not verified (and why) / Open risks. Never claim a fix or a scan that did not happen.",
  ];

  const ruleLine = (r: Rule) =>
    `- ${r.id} (${r.severity}) ${r.title}: ${r.prevention[0] ?? r.description}`;
  const build = (count: number): string => {
    const shown = rules.slice(0, count);
    const lessons = (input.lessons ?? []).slice(0, 5);
    const lines = [...head, ...operating, ...dangerous, ...verify];
    if (lessons.length > 0) {
      lines.push(
        "",
        "**Approved lessons for this project:**",
        ...lessons.map((l) => `- ${l.id} ${l.title}: ${l.guidance.slice(0, 240)}`),
      );
    }
    if (rules.length > 0) {
      lines.push("", "**Rules for this project:**", ...shown.map(ruleLine));
      if (shown.length < rules.length) {
        lines.push(
          `- ${rules.length - shown.length} more rule(s): run \`aegis rules list\` for the full list.`,
        );
      }
    }
    return lines.join("\n").trimEnd() + "\n";
  };

  for (let n = rules.length; n >= 0; n--) {
    const text = build(n);
    if (byteLength(text) <= COMPACT_BUDGET_BYTES) return text;
  }
  return build(0);
}

/**
 * Text to paste into ChatGPT (Customize ChatGPT, or a Project's instructions).
 * ChatGPT in the browser cannot read repository files or run commands, so the text tells it
 * to say so honestly and to work from check output that the person pastes back.
 */
export function buildChatGptInstructions(input: InstructionInput): string {
  const text = [
    "AEGIS coding rules. Inspect before coding, protect during coding, verify after coding.",
    "- Ask for the relevant code before changing it. Never invent files, APIs or package versions.",
    "- Make the smallest change that fixes the root cause. No unrelated refactors.",
    "- Never: build SQL or HTML from untrusted strings, hardcode secrets, trust client-side auth checks, skip input validation, or disable a check or test to get green.",
    "- Do not add or upgrade dependencies without telling me why.",
    "- Ask me before anything destructive (deleting data, rewriting git history, production changes).",
    `- You cannot run code. Never say something is fixed, secure or tested. Give me the exact command to run (\`${input.checkCommand}\`) and ask me to paste the output, then fix from that output.`,
    `- After ${input.maxAttempts} failed attempts at one problem, stop and summarize what is unresolved.`,
    "- End with: Changed / Verified (only what I confirmed) / Not verified / Risks.",
  ].join("\n");
  return text;
}

